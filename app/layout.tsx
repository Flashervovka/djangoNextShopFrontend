import './globals.css';

import type { Metadata } from 'next';
import { Geist, Geist_Mono, Inter } from 'next/font/google';
import { Suspense } from 'react';

import { AppSidebar } from '@/app/components/pages/components';
import { SidebarInset, SidebarProvider, SidebarTrigger } from '@/components/ui/sidebar';
import { getCategories } from '@/lib/fetchApi';
import { cn } from '@/lib/utils';

const inter = Inter({ subsets: ['latin'], variable: '--font-sans' });

const geistSans = Geist({
  variable: '--font-geist-sans',
  subsets: ['latin'],
});

const geistMono = Geist_Mono({
  variable: '--font-geist-mono',
  subsets: ['latin'],
});

export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
};

async function SidebarLoader() {
  const categories = await getCategories();
  // TODO сделать типизацию правильной, когда с бека будет приходить правильная пагинация
  return <AppSidebar data={categories} />;
}

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html
      lang="ru"
      className={cn('h-full', geistSans.variable, geistMono.variable, inter.variable, 'font-sans')}
    >
      <body className="bg-background text-foreground min-h-screen overflow-hidden antialiased">
        <SidebarProvider>
          <Suspense fallback={<div className="bg-muted/30 w-64 shrink-0" />}>
            <SidebarLoader />
          </Suspense>

          <SidebarInset
            className={cn(
              'overflow-y-auto p-6',
              'md:peer-data-[variant=inset]:m-0',
              'md:peer-data-[variant=inset]:rounded-none',
              'md:peer-data-[variant=inset]:shadow-none',
              'md:peer-data-[variant=inset]:peer-data-[state=collapsed]:ml-0',
              'bg-green-700'
            )}
          >
            <header className="flex items-center justify-between border-b pb-4">
              <SidebarTrigger className="md:hidden" />
              <span className="text-lg font-medium">text in header</span>
            </header>

            <div className="mt-6 flex-1">{children}</div>

            <footer className="mt-auto">
              <span className="text-xl font-semibold">Footer item here</span>
            </footer>
          </SidebarInset>
        </SidebarProvider>
      </body>
    </html>
  );
}
